import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const target = path.join(root, 'output/apf3/figma');
const files = [
 ['Inicio paciente', '02-patient-home.png'], ['Tratamiento paciente', '03-patient-treatment.png'],
 ['Formulario de medición', '04-patient-measurement.png'], ['Error de medición', '05-measurement-error.png'],
 ['Citas del paciente', '08-patient-appointments.png'], ['Respuesta de toma', '12-dose-recorded.png'],
 ['Resumen del cuidador', '17-caregiver-dashboard.png'], ['Tratamiento y existencias', '18-caregiver-medications.png'],
 ['Texto ampliado en línea base', '16-patient-text-200.png'], ['Estado vacío', '23-caregiver-empty.png'],
];
const assets = files.map(([name,file]) => {
 const relative = 'output/apf3/evidence/baseline/' + file;
 const bytes = fs.readFileSync(path.join(root,relative));
 return { name, file: relative, base64: bytes.toString('base64'), width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
});
execFileSync(process.execPath, [path.join(root,'frontend/node_modules/typescript/bin/tsc'), '-p', path.join(here,'tsconfig.json')], {stdio:'inherit'});
fs.mkdirSync(target,{recursive:true});
const code = `// Embedded real baseline captures; generated by tools/apf3/figma/build.mjs.\nconst BASELINE_ASSETS = ${JSON.stringify(assets)};\n` + fs.readFileSync(path.join(here,'compiled/plugin.js'),'utf8');
fs.writeFileSync(path.join(target,'code.js'),code,'utf8');
fs.copyFileSync(path.join(here,'manifest.json'),path.join(target,'manifest.json'));
fs.copyFileSync(path.join(here,'README.md'),path.join(target,'LEEME.md'));
const baselineAudit = JSON.parse(fs.readFileSync(path.join(root,'output/apf3/evidence/baseline/audit.json'),'utf8'));
fs.writeFileSync(path.join(target,'estado.json'),JSON.stringify({
 status:'PAQUETE LOCAL GENERADO; NO EJECUTADO NI PUBLICADO EN FIGMA',
 generatedAt:new Date().toISOString(),
 expectedPages:6,
 expectedScreens:105,
 baselineCommit:baselineAudit.metadata.baselineCommit,
 baselineCaptureDate:baselineAudit.metadata.timestamp,
 baselineAssets:assets.map(({base64,...meta})=>meta),
 designCase:'Datos sintéticos fijos, no resultados de usuarios. Estado inicial de inventario antes de tomas.',
 pending:['Importar y ejecutar plugin en Figma','Inspeccionar páginas,componentes y prototipo','Ejecutar Stark y guardar evidencia','Compartir solo lectura y verificar en incógnito','Sesiones con participantes y tecnologías de apoyo']
},null,2));
console.log(JSON.stringify({output:target,codeBytes:Buffer.byteLength(code),assets:assets.length,dimensions:assets.map(a=>[a.name,a.width,a.height]),status:'local package; Figma not executed'},null,2));
