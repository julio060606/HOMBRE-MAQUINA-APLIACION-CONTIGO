-- Browser-to-browser support. Audio is never recorded in these tables.
CREATE TABLE telemetry.support_sessions (
    id VARCHAR(36) PRIMARY KEY,
    patient_id VARCHAR(36) NOT NULL REFERENCES clinical.patients(id),
    patient_name VARCHAR(255) NOT NULL,
    caller_id VARCHAR(36) NOT NULL REFERENCES auth.users(id),
    responder_id VARCHAR(36) REFERENCES auth.users(id),
    responder_name VARCHAR(255),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_reason VARCHAR(120),
    alert_id VARCHAR(36) NOT NULL REFERENCES telemetry.alert_events(id),
    operation_id VARCHAR(100) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    CONSTRAINT support_session_operation UNIQUE (caller_id, operation_id),
    CONSTRAINT support_session_status CHECK (status IN ('WAITING', 'ACCEPTED', 'ENDED'))
);
CREATE INDEX support_session_patient ON telemetry.support_sessions(patient_id, created_at);

CREATE TABLE telemetry.support_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36) NOT NULL REFERENCES telemetry.support_sessions(id),
    sender_id VARCHAR(36) NOT NULL REFERENCES auth.users(id),
    sender_name VARCHAR(255) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    operation_id VARCHAR(100) NOT NULL,
    CONSTRAINT support_event_operation UNIQUE (session_id, sender_id, operation_id),
    CONSTRAINT support_event_kind CHECK (kind IN ('TEXT', 'OFFER', 'ANSWER', 'ICE'))
);
CREATE INDEX support_event_cursor ON telemetry.support_events(session_id, id);
